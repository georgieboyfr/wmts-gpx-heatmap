const SERVER_PATTERNS = {
  en: [
    [/^Nouvel essai de (\d+) fichier\(s\)$/, (m) => `Retry of ${m[1]} ${plural(+m[1], "file", "files")}`],
    [/^Import automatique : (\d+) fichier\(s\)(?:, (\d+) retiré\(s\))?$/,
      (m) => `Automatic import: ${m[1]} ${plural(+m[1], "file", "files")}` + (m[2] ? `, ${m[2]} removed` : "")],
  ],
};

function detectLang() {
  try {
    const saved = localStorage.getItem("admin-lang");
    if (LANGS.includes(saved)) return saved;
  } catch (e) { /* stockage indisponible */ }
  return (navigator.language || "").toLowerCase().startsWith("fr") ? "fr" : "en";
}

const LANG = detectLang();
const LOCALE = LANG === "fr" ? "fr-FR" : "en-GB";

function t(key, values = {}) {
  const msg = MESSAGES[LANG][key] ?? MESSAGES.fr[key] ?? key;
  return typeof msg === "function" ? msg(values) : msg;
}

// texte venant du serveur (libellé de tâche, phase, clé de résultat)
function ts(text) {
  if (text == null) return text;
  const exact = (SERVER_TEXTS[LANG] || {})[text];
  if (exact) return exact;
  for (const [re, fn] of SERVER_PATTERNS[LANG] || []) {
    const m = String(text).match(re);
    if (m) return fn(m);
  }
  return text;
}

function setLang(lang) {
  try { localStorage.setItem("admin-lang", lang); } catch (e) { /* stockage indisponible */ }
  location.reload();
}

function applyTranslations(root = document) {
  document.documentElement.lang = LANG;
  document.title = t("app.title");
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  for (const attr of ["placeholder", "title"]) {
    root.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => el.setAttribute(attr, t(el.dataset[`i18n${attr[0].toUpperCase()}${attr.slice(1)}`])));
  }
  root.querySelectorAll("[data-lang]").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === LANG);
    b.setAttribute("aria-pressed", String(b.dataset.lang === LANG));
    b.addEventListener("click", () => { if (b.dataset.lang !== LANG) setLang(b.dataset.lang); });
  });
}
